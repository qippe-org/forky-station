using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Qippe.Whitelist.UI;

/// <summary>
/// The screen shown to a player the whitelist is blocking, offering only the application form.
/// </summary>
/// <remarks>
/// The form itself is the existing <c>WhitelistApplyEui</c>, opened through the <c>whitelistapply</c> console command
/// so there is a single code path for submitting an application.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class WhitelistApplicationScreen : UIScreen
{
    [Dependency] private IClientConsoleHost _console = default!;

    public WhitelistApplicationScreen()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // UIScreen is a LayoutContainer, which places children by anchor and ignores the alignment
        // properties. Anchoring both children to the whole screen gives the panel a full screen rect, so its
        // own HorizontalAlignment/VerticalAlignment can then shrink and center it, and lets the background fill.
        SetAnchorPreset(Background, LayoutPreset.Wide);
        SetAnchorPreset(MainPanel, LayoutPreset.Wide);

        TitleLabel.Text = Loc.GetString("whitelist-application-screen-title");
        DescriptionLabel.SetMarkup(Loc.GetString("whitelist-application-screen-description"));

        ApplyButton.OnPressed += _ => _console.ExecuteCommand("whitelistapply");
        DisconnectButton.OnPressed += _ => _console.ExecuteCommand("disconnect");
    }

    public void SetState(bool hasApplication)
    {
        // With an application already on file the form is read-only, so point the player at the review instead of
        // letting them press a button that only opens a window they cannot type in.
        StatusLabel.Visible = hasApplication;
        StatusLabel.Text = hasApplication
            ? Loc.GetString("whitelist-application-screen-pending")
            : string.Empty;

        ApplyButton.Disabled = hasApplication;
    }
}
