using Content.Shared._Qippe.Whitelist;
using Content.Shared.Database;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Qippe.Whitelist;

[GenerateTypedNameReferences]
public sealed partial class WhitelistApplicationsWindow : DefaultWindow
{
    public WhitelistApplicationsWindow()
    {
        RobustXamlLoader.Load(this);

        Title = Loc.GetString("whitelist-application-window-title");

        Tabs.SetTabTitle(0, Loc.GetString("whitelist-application-tab-all"));
        Tabs.SetTabTitle(1, Loc.GetString("whitelist-application-tab-pending"));
        Tabs.SetTabTitle(2, Loc.GetString("whitelist-application-tab-approved"));
        Tabs.SetTabTitle(3, Loc.GetString("whitelist-application-tab-denied"));

        PendingList.SetEmptyText(Loc.GetString("whitelist-application-empty-pending"));
        ApprovedList.SetEmptyText(Loc.GetString("whitelist-application-empty-approved"));
        DeniedList.SetEmptyText(Loc.GetString("whitelist-application-empty-denied"));
        AllList.SetEmptyText(Loc.GetString("whitelist-application-empty-all"));
    }

    /// <summary>
    /// Updates the tab titles with the number of rows each one holds.
    /// </summary>
    public void SetCounts(List<SharedWhitelistApplication> applications)
    {
        SetCount(0, "whitelist-application-tab-all", applications.Count);
        SetCount(1, "whitelist-application-tab-pending", CountOf(applications, WhitelistApplicationStatus.Pending));
        SetCount(2, "whitelist-application-tab-approved", CountOf(applications, WhitelistApplicationStatus.Approved));
        SetCount(3, "whitelist-application-tab-denied", CountOf(applications, WhitelistApplicationStatus.Denied));
    }

    private static int CountOf(List<SharedWhitelistApplication> applications, WhitelistApplicationStatus status)
    {
        var count = 0;

        foreach (var application in applications)
        {
            if (application.Status == status)
                count++;
        }

        return count;
    }

    private void SetCount(int index, string key, int count)
    {
        Tabs.SetTabTitle(index, Loc.GetString("whitelist-application-tab-titled",
            ("title", Loc.GetString(key)),
            ("count", count)));
    }
}


