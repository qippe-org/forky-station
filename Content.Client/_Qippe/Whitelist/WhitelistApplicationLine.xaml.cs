using Content.Shared._Qippe.Whitelist;
using Content.Shared.Database;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Qippe.Whitelist;

[GenerateTypedNameReferences]
public sealed partial class WhitelistApplicationLine : BoxContainer
{
    public event Action<int>? ApprovePressed;
    public event Action<int>? DenyPressed;

    private readonly SharedWhitelistApplication _application;
    private WhitelistApplicationPopup? _popup;

    public WhitelistApplicationLine(SharedWhitelistApplication application, bool canReview)
    {
        RobustXamlLoader.Load(this);

        _application = application;

        IdLabel.Text = $"#{application.Id}";
        PlayerLabel.Text = application.PlayerName;
        StatusLabel.Text = Loc.GetString($"whitelist-application-status-{application.Status.ToString().ToLowerInvariant()}");
        CreatedLabel.Text = FormatDate(application.CreatedAt);
        ReviewerLabel.Text = application.ReviewedByName ?? Loc.GetString("whitelist-application-no-reviewer");

        ApproveButton.OnPressed += _ => ApprovePressed?.Invoke(application.Id);
        DenyButton.OnPressed += _ => DenyPressed?.Invoke(application.Id);
        ViewButton.OnPressed += _ => OpenPopup();

        // Nothing to do on a row that was already decided.
        ApproveButton.Disabled = !canReview || application.Status != WhitelistApplicationStatus.Pending;
        DenyButton.Disabled = !canReview || application.Status != WhitelistApplicationStatus.Pending;
        ApproveButton.Visible = canReview;
        DenyButton.Visible = canReview;
    }

    /// <summary>
    /// Shows the full application text in a popup, replacing any popup this row opened before.
    /// </summary>
    internal void OpenPopup()
    {
        _popup?.Close();
        _popup = null;

        // OpenAtMouse parents the popup in the modal root itself, so it must not be added manually.
        var popup = new WhitelistApplicationPopup(_application);
        popup.OnPopupHide += () =>
        {
            if (_popup == popup)
                _popup = null;
        };

        _popup = popup;
        popup.OpenAtMouse();
    }

    /// <summary>
    /// The popup this row currently has open, if any.
    /// </summary>
    internal WhitelistApplicationPopup? Popup => _popup;

    private static string FormatDate(DateTime date)
    {
        return date.ToString("yyyy-MM-dd HH:mm") + " UTC";
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (!disposing)
            return;

        // The popup lives in the modal root, not under this control, so it needs an explicit close.
        _popup?.Close();
        _popup = null;

        ApprovePressed = null;
        DenyPressed = null;
    }
}
