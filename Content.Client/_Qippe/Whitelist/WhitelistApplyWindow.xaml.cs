using Content.Client.UserInterface.Controls;
using Content.Shared._Qippe.Whitelist;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Qippe.Whitelist;

[GenerateTypedNameReferences]
public sealed partial class WhitelistApplyWindow : FancyWindow
{
    /// <summary>
    /// Raised when the player submits the form.
    /// </summary>
    public event Action<string>? SubmitPressed;

    private int _maxLength = WhitelistApplicationConstants.MaxMessageLength;
    private bool _enabled;

    public WhitelistApplyWindow()
    {
        RobustXamlLoader.Load(this);

        DescriptionLabel.Text = Loc.GetString("whitelist-application-form-description");
        MessageEdit.Placeholder = new Rope.Leaf(Loc.GetString("whitelist-application-form-placeholder"));

        MessageEdit.OnTextChanged += _ => UpdateCounter();
        SubmitButton.OnPressed += _ => SubmitPressed?.Invoke(Rope.Collapse(MessageEdit.TextRope));

        UpdateCounter();
    }

    public void SetState(WhitelistApplyEuiState state)
    {
        _maxLength = state.MaxLength;
        _enabled = state.Enabled;

        var hasExisting = state.Existing != null;

        // A player only gets one application, so show what they wrote instead of the editor.
        if (state.Existing is { } existing)
        {
            var status = Loc.GetString($"whitelist-application-status-{existing.Status.ToString().ToLowerInvariant()}");
            StatusLabel.Text = Loc.GetString("whitelist-application-form-existing",
                ("status", status),
                ("id", existing.Id));
            StatusLabel.Visible = true;

            if (existing.ReviewedByName is { } reviewer)
            {
                ReviewerLabel.Text = existing.ReviewedAt is { } reviewedAt
                    ? Loc.GetString("whitelist-application-form-reviewer-date",
                        ("reviewer", reviewer),
                        ("reviewed", reviewedAt.ToString("yyyy-MM-dd HH:mm") + " UTC"))
                    : Loc.GetString("whitelist-application-form-reviewer", ("reviewer", reviewer));

                ReviewerLabel.Visible = true;
            }
            else
            {
                ReviewerLabel.Visible = false;
            }

            MessageEdit.TextRope = new Rope.Leaf(existing.Message);
        }
        else
        {
            StatusLabel.Visible = false;
            ReviewerLabel.Visible = false;
        }

        MessageEdit.Editable = !hasExisting && state.Enabled;
        SubmitButton.Visible = !hasExisting;

        if (!state.Enabled)
            DescriptionLabel.Text = Loc.GetString("whitelist-application-form-disabled");

        UpdateCounter();
    }

    public void ShowResult(WhitelistApplicationSubmitResult result)
    {
        CounterLabel.Text = result switch
        {
            WhitelistApplicationSubmitResult.EmptyMessage => Loc.GetString("whitelist-application-reject-empty"),
            WhitelistApplicationSubmitResult.MessageTooLong => Loc.GetString("whitelist-application-reject-too-long",
                ("max", _maxLength)),
            WhitelistApplicationSubmitResult.AlreadyApplied => Loc.GetString("whitelist-application-reject-already-applied"),
            _ => Loc.GetString("whitelist-application-reject-failed"),
        };
    }

    private void UpdateCounter()
    {
        var length = MessageEdit.TextLength;

        CounterLabel.Text = Loc.GetString("whitelist-application-form-counter",
            ("current", length),
            ("max", _maxLength));

        SubmitButton.Disabled = !_enabled || !MessageEdit.Editable || !IsValidLength();
    }

    private bool IsValidLength()
    {
        var text = Rope.Collapse(MessageEdit.TextRope);

        if (string.IsNullOrWhiteSpace(text))
            return false;

        return MessageEdit.TextLength <= _maxLength;
    }
}

