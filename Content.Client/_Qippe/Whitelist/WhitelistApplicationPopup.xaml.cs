using Content.Shared._Qippe.Whitelist;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Qippe.Whitelist;

[GenerateTypedNameReferences]
public sealed partial class WhitelistApplicationPopup : Popup
{
    public WhitelistApplicationPopup(SharedWhitelistApplication application)
    {
        RobustXamlLoader.Load(this);

        HeaderLabel.Text = Loc.GetString("whitelist-application-popup-title",
            ("id", application.Id),
            ("player", application.PlayerName));

        var status = Loc.GetString($"whitelist-application-status-{application.Status.ToString().ToLowerInvariant()}");
        var created = application.CreatedAt.ToString("yyyy-MM-dd HH:mm") + " UTC";

        if (application.ReviewedAt is { } reviewedAt && application.ReviewedByName is { } reviewer)
        {
            DetailsLabel.Text = Loc.GetString("whitelist-application-popup-details-reviewed",
                ("status", status),
                ("created", created),
                ("reviewer", reviewer),
                ("reviewed", reviewedAt.ToString("yyyy-MM-dd HH:mm") + " UTC"));
        }
        else
        {
            DetailsLabel.Text = Loc.GetString("whitelist-application-popup-details",
                ("status", status),
                ("created", created));
        }

        // Player supplied text, keep it escaped instead of parsing markup.
        MessageLabel.SetMessage(application.Message);
    }
}
