using Content.Client.Administration.UI.CustomControls;
using Content.Shared._Qippe.Whitelist;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Qippe.Whitelist;

[GenerateTypedNameReferences]
public sealed partial class WhitelistApplicationListControl : Control
{
    /// <summary>
    /// Raised when an admin approves or denies a row.
    /// </summary>
    public event Action<int>? ApprovePressed;
    public event Action<int>? DenyPressed;

    private readonly List<WhitelistApplicationLine> _lines = [];
    private string _emptyText = string.Empty;

    public WhitelistApplicationListControl()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetEmptyText(string text)
    {
        _emptyText = text;
    }

    public void SetApplications(List<SharedWhitelistApplication> applications, bool canReview)
    {
        // Keep the header at index 0 and drop every row from the previous state.
        for (var i = Applications.ChildCount - 1; i >= 1; i--)
        {
            Applications.GetChild(i).Dispose();
        }

        _lines.Clear();

        foreach (var application in applications)
        {
            var line = new WhitelistApplicationLine(application, canReview);
            line.ApprovePressed += id => ApprovePressed?.Invoke(id);
            line.DenyPressed += id => DenyPressed?.Invoke(id);

            _lines.Add(line);
            Applications.AddChild(new HSeparator());
            Applications.AddChild(line);
        }

        EmptyLabel.Text = _emptyText;
        EmptyLabel.Visible = applications.Count == 0;
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (!disposing)
            return;

        ApprovePressed = null;
        DenyPressed = null;
        _lines.Clear();
    }
}

